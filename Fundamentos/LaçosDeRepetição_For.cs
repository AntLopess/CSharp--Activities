using System;
namespace LaçosDeRepetição
{
    class LaçosDeRepetição
    {
        static void Main(string[] args)
        {
            for (int i = 1; i<=5; i++) // Laço que começa em 1 e vai até 5.
            {
                Console.WriteLine("Contagem: " + i);// Exibe o valor de i a cada interação.
            }
            Console.ReadLine();
        }
    }
}
